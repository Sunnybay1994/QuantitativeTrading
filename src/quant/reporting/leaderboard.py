"""Render the result registry, retaining the pre-machine leaderboard backup."""
import argparse
import datetime as dt
from pathlib import Path

import polars as pl

from quant.reporting.experiment_registry import DEFAULT_LEADERBOARD, DEFAULT_REGISTRY

MARKER = '<!-- Generated by quant.reporting.leaderboard -->'


def _fmt(value: float | None, percent: bool = False) -> str:
    return '—' if value is None else format(value, '.2%' if percent else '.2f')


def write_leaderboard(registry: Path = DEFAULT_REGISTRY, output: Path = DEFAULT_LEADERBOARD) -> None:
    rows = pl.read_parquet(registry).to_dicts()
    if output.exists() and MARKER not in output.read_text(encoding='utf-8'):
        stamp = dt.datetime.now().strftime('%Y%m%dT%H%M%S%f')
        (registry.parent/f'leaderboard_before_machine_{stamp}.md').write_bytes(output.read_bytes())
    # Show latest primary variants per hypothesis; the registry retains every historical run.
    latest = {}
    for row in sorted(rows, key=lambda r: (r['result_time'], r['run_path'])):
        if row['primary']:
            latest[row['experiment_id'], row['variant']] = row
    featured = [r for r in rows if 'q1b_original_p4_equal_weight_reports_' in r['run_path'] and r['primary']]
    recent = sorted(latest.values(), key=lambda r: (r['conclusion'] == 'PAPER_CANDIDATE',
                    r['result_time']), reverse=True)
    chosen = {(r['run_path'], r['variant']): r for r in featured+recent[:45]}
    lines = ['# 实验排行榜', '', MARKER, '',
        f'注册表共 {len(rows)} 个运行/变体；本页展示最新主组合和 Q1 修正对照，全部历史见注册表。',
        f'[完整结果注册表]({registry.resolve().as_posix()})', '',
        '年化/回撤/超额为百分比；三档按 0.5× / 1× / 2× 成本排列，换手为单边年化倍数。缺失字段显示 —。',
        '结论沿用各运行原判定；不同测量口径与历史版本不混作新的准入证据。', '',
        '|实验 / 变体|持股区间|CAGR 三档|Sharpe 三档|最大回撤三档|换手三档|超额最强基准三档|结论|产物|',
        '|---|---|---|---|---|---|---|---|---|']
    for row in chosen.values():
        label = row['experiment_id']
        if 'q1b_original_p4_equal_weight_reports_' in row['run_path']:
            label = 'Q1 修正值'
        if 'r1_q10_calendar_turnover_' in row['run_path']:
            label = 'Q10 SUE v2 新换手口径'
        cells = [f"{label} / {row['variant']}", f"{row['start']}—{row['end']}"]
        for metric in ('cagr', 'sharpe', 'mdd', 'turnover', 'excess'):
            cells.append(' / '.join(_fmt(row[f'{metric}_{suffix}'], metric in ('cagr', 'mdd', 'excess'))
                                   for suffix in ('0_5x', '1x', '2x')))
        cells += [row['conclusion'], f"[报告]({row['report_path']})"]
        lines.append('|'+ '|'.join(cells)+'|')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines)+'\n', encoding='utf-8')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--registry', type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument('--output', type=Path, default=DEFAULT_LEADERBOARD)
    args = parser.parse_args()
    write_leaderboard(args.registry, args.output)


if __name__ == '__main__':
    main()
