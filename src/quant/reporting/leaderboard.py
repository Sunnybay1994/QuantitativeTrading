"""Render the result registry, retaining the pre-machine leaderboard backup."""
import argparse
import datetime as dt
from pathlib import Path

import polars as pl

from quant.reporting.experiment_registry import DEFAULT_LEADERBOARD, DEFAULT_REGISTRY

MARKER = '<!-- Generated by quant.reporting.leaderboard -->'
DEFAULT_FACTOR_LEADERBOARD = DEFAULT_LEADERBOARD.with_name('排行榜_因子.md')


def _fmt(value: float | None, percent: bool = False) -> str:
    return '—' if value is None else format(value, '.2%' if percent else '.2f')


def infer_level(run_path: str, level: str | None = None) -> str:
    if level in ('factor', 'strategy'):
        return level
    path = run_path.replace('\\', '/')
    if '/artifacts/factors/' in path or path.startswith('artifacts/factors/'):
        return 'factor'
    return 'strategy'


def _label(row: dict) -> str:
    label = row['experiment_id']
    path = row['run_path'].replace('\\', '/')
    if 'q1b_original_p4_equal_weight_reports_' in path:
        return 'Q1 修正值'
    if 'r1_q10_calendar_turnover_' in path or 'r1_q10_rolling_' in path:
        return 'Q10 SUE v2'
    return label


def _render(rows: list[dict], *, title: str, intro: str, limit: int | None) -> list[str]:
    latest = {}
    for row in sorted(rows, key=lambda r: (r['result_time'], r['run_path'])):
        if row.get('primary'):
            latest[row['experiment_id'], row['variant']] = row
    featured = [r for r in rows if 'q1b_original_p4_equal_weight_reports_' in r['run_path'] and r.get('primary')]
    recent = sorted(
        latest.values(),
        key=lambda r: (r['conclusion'] == 'PAPER_CANDIDATE', r.get('result_time') or ''),
        reverse=True,
    )
    chosen = list({(r['run_path'], r['variant']): r for r in featured + recent}.values())
    if limit is not None:
        # Keep Q10 first when present, then remaining up to limit.
        q10 = [r for r in chosen if 'q10' in r['run_path'].replace('\\', '/').lower()
               or 'q10' in str(r.get('experiment_id', '')).lower()]
        rest = [r for r in chosen if r not in q10]
        chosen = (q10 + rest)[:limit]
        # Stable: ensure first row is Q10 PAPER_CANDIDATE budgeted when available.
        preferred = next(
            (r for r in chosen
             if r.get('conclusion') == 'PAPER_CANDIDATE' and r.get('variant') == 'budgeted'
             and 'q10_sue_v2_turnover' in r['run_path'].replace('\\', '/').lower()),
            None,
        )
        if preferred is None:
            preferred = next(
                (r for r in chosen
                 if r.get('variant') == 'budgeted'
                 and 'q10_sue_v2_turnover' in r['run_path'].replace('\\', '/').lower()),
                None,
            )
        if preferred is not None:
            chosen = [preferred] + [r for r in chosen if r is not preferred]
    lines = [f'# {title}', '', MARKER, '', intro, '',
             '年化/回撤/超额为百分比；三档按 0.5× / 1× / 2× 成本排列，换手为单边年化倍数。缺失字段显示 —。',
             '结论沿用各运行原判定；不同测量口径与历史版本不混作新的准入证据。',
             'IS/OOS：设计日 / 数据截止 / 样本外起点月 / 样本外月数 / 范围（D2）。', '',
             '|实验 / 变体|持股区间|设计日|数据截止|OOS起点|OOS月数|范围|CAGR 三档|Sharpe 三档|最大回撤三档|换手三档|超额最强基准三档|结论|产物|',
             '|---|---|---|---|---|---:|---|---|---|---|---|---|---|---|']
    for row in chosen:
        cells = [f"{_label(row)} / {row['variant']}", f"{row['start']}—{row['end']}",
                 str(row.get('design_date') or '—'), str(row.get('data_end') or '—'),
                 str(row.get('oos_start') or '—'),
                 '—' if row.get('oos_months') is None else str(row.get('oos_months')),
                 str(row.get('sample_scope') or '—')]
        for metric in ('cagr', 'sharpe', 'mdd', 'turnover', 'excess'):
            cells.append(' / '.join(_fmt(row.get(f'{metric}_{suffix}'), metric in ('cagr', 'mdd', 'excess'))
                                   for suffix in ('0_5x', '1x', '2x')))
        cells += [row['conclusion'], f"[报告]({row['report_path']})"]
        lines.append('|' + '|'.join(cells) + '|')
    return lines


def write_leaderboard(registry: Path = DEFAULT_REGISTRY, output: Path = DEFAULT_LEADERBOARD,
                      factor_output: Path = DEFAULT_FACTOR_LEADERBOARD) -> None:
    frame = pl.read_parquet(registry)
    if 'level' not in frame.columns:
        frame = frame.with_columns(pl.lit(None).cast(pl.Utf8).alias('level'))
    rows = frame.to_dicts()
    from quant.reporting.sample_scope import months_between, q10_oos_defaults
    for row in rows:
        row['level'] = infer_level(row['run_path'], row.get('level'))
        path = row['run_path'].replace('\\', '/').lower()
        if 'q10' in path or 'q10' in str(row.get('experiment_id', '')).lower():
            defaults = q10_oos_defaults()
            row['design_date'] = row.get('design_date') or defaults['design_date']
            row['oos_start'] = defaults['oos_start']
            row['oos_months'] = months_between(defaults['oos_start'], dt.date.today())
            row['sample_scope'] = defaults['sample_scope']
            row['data_end'] = row.get('data_end') or row.get('end')
    if output.exists() and MARKER not in output.read_text(encoding='utf-8'):
        stamp = dt.datetime.now().strftime('%Y%m%dT%H%M%S%f')
        (registry.parent / f'leaderboard_before_machine_{stamp}.md').write_bytes(output.read_bytes())
    strategies = [r for r in rows if r['level'] == 'strategy']
    factors = [r for r in rows if r['level'] == 'factor']
    strategy_lines = _render(
        strategies,
        title='实验排行榜（策略级）',
        intro=(
            f'注册表共 {len(rows)} 行；本页仅策略级 {len(strategies)} 行（B6）。'
            f'因子级见 [排行榜_因子.md]({factor_output.name})；全部历史见注册表 '
            f'[experiments.parquet]({registry.resolve().as_posix()})。'
        ),
        limit=45,
    )
    factor_lines = _render(
        factors,
        title='实验排行榜（因子级）',
        intro=f'因子级运行 {len(factors)} 行；策略级见 [排行榜.md]({output.name})。',
        limit=80,
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(strategy_lines) + '\n', encoding='utf-8')
    factor_output.write_text('\n'.join(factor_lines) + '\n', encoding='utf-8')
    # Persist inferred levels without rebuilding unrelated columns.
    levels = pl.DataFrame({
        'run_path': [r['run_path'] for r in rows],
        'variant': [r['variant'] for r in rows],
        'level': [r['level'] for r in rows],
    })
    refreshed = frame.drop('level', strict=False).join(levels, on=['run_path', 'variant'], how='left')
    temporary = registry.with_suffix('.parquet.tmp')
    refreshed.write_parquet(temporary)
    temporary.replace(registry)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--registry', type=Path, default=DEFAULT_REGISTRY)
    parser.add_argument('--output', type=Path, default=DEFAULT_LEADERBOARD)
    parser.add_argument('--factor-output', type=Path, default=DEFAULT_FACTOR_LEADERBOARD)
    args = parser.parse_args()
    write_leaderboard(args.registry, args.output, args.factor_output)


if __name__ == '__main__':
    main()
